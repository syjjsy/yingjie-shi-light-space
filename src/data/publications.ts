export function doiUrl(doi: string) {
  return `https://doi.org/${doi}`;
}

export function bibtexFor(item: Publication) {
  const key = `shi${item.year}${item.title.split(/\s+/)[0].toLowerCase().replace(/[^a-z]/g, "")}`;
  const entry = item.type === "conference" ? "inproceedings" : item.type === "preprint" ? "misc" : "article";
  const fields = [
    `  title = {${item.title}}`,
    `  author = {${item.authors.join(" and ")}}`,
    `  year = {${item.year}}`,
    `  ${entry === "inproceedings" ? "booktitle" : "journal"} = {${item.venue}}`,
    item.volume && `  volume = {${item.volume}}`,
    item.issue && `  number = {${item.issue}}`,
    item.pages && `  pages = {${item.pages}}`,
    `  doi = {${item.doi}}`,
  ].filter(Boolean);
  return `@${entry}{${key},\n${fields.join(",\n")}\n}`;
}
